import { SecretClient } from "@azure/keyvault-secrets";

export interface RotationResult {
  name: string;
  newVersion: string;
  previousVersion?: string;
  expiresOn: Date;
}

/**
 * Helper that safely rotates a Key Vault secret:
 *
 * 1. Creates a new version of the secret with an updated value and expiry.
 * 2. Optionally cleans up old versions by performing a soft-delete and
 *    waiting for completion, then purging the deleted secret.
 *
 * The cleanup path respects Key Vault's soft-delete behaviour — the
 * long-running delete poller is awaited before purge is attempted.
 */
export class SecretRotationHelper {
  constructor(private readonly client: SecretClient) {}

  /**
   * Create a new version of an existing secret.
   *
   * @param name       Secret name (version is auto-generated by Key Vault).
   * @param newValue   The new secret value.
   * @param expiresOn  When the new version should expire.
   */
  async rotateSecret(
    name: string,
    newValue: string,
    expiresOn: Date
  ): Promise<RotationResult> {
    // Capture the current version before overwriting.
    let previousVersion: string | undefined;
    try {
      const current = await this.client.getSecret(name);
      previousVersion = current.properties.version;
    } catch {
      // Secret may not exist yet — that's fine.
    }

    const updated = await this.client.setSecret(name, newValue, {
      expiresOn,
    });

    return {
      name,
      newVersion: updated.properties.version!,
      previousVersion,
      expiresOn,
    };
  }

  /**
   * Delete a secret using the long-running operation and wait until
   * Key Vault has fully processed the soft-delete, then purge it so
   * the name can be reused immediately.
   */
  async deleteAndPurgeSecret(name: string): Promise<void> {
    // beginDeleteSecret returns a poller; pollUntilDone waits for the
    // soft-delete to complete.
    const poller = await this.client.beginDeleteSecret(name);
    await poller.pollUntilDone();

    // Now that the secret is in a soft-deleted state, purge it.
    await this.client.purgeDeletedSecret(name);
  }
}
